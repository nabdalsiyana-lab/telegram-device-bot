def load_devices():
  devices = {}
  for line in RAW_DATA.strip().split("\n"):
    if not line.strip():
      continue
    parts = line.split("|")
    dev_id = parts[0].strip()
    name = parts[1].strip() if len(parts) > 1 else ""
    phone = parts[2].strip() if len(parts) > 2 else ""
    devices[dev_id] = {"name": name, "phone": phone}
  return devices


DEVICES = load_devices()


async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
  welcome = (
      "أهلاً بك في بوت إدارة الأجهزة! 🤖\n\n"
      "يمكنك البحث كالتالي:\n"
      "1️⃣ أرسل **رقم الجهاز** مباشرة (مثال: `260`).\n"
      "2️⃣ أرسل **اسم العميل** للبحث عنه (مثال: `احمد`)."
  )
  await update.message.reply_text(welcome, parse_mode="Markdown")


async def handle_search(update: Update, context: ContextTypes.DEFAULT_TYPE):
  query = update.message.text.strip()

  if query in DEVICES:
    dev = DEVICES[query]
    phone_str = (
        f"[{dev['phone']}](tel:{dev['phone']})" if dev["phone"] else "لا يوجد"
    )
    msg = (
        f"🔢 **رقم الجهاز:** {query}\n"
        f"👤 **اسم العميل:** {dev['name']}\n"
        f"📱 **رقم الهاتف:** {phone_str}\n"
        f"📝 **الملاحظة:** "
    )
    await update.message.reply_text(msg, parse_mode="Markdown")
    return

  results = []
  for dev_id, dev_info in DEVICES.items():
    if query.lower() in dev_info["name"].lower():
      phone_str = (
          f"[{dev_info['phone']}](tel:{dev_info['phone']})"
          if dev_info["phone"]
          else "لا يوجد"
      )
      results.append(
          f"🔢 **رقم الجهاز:** {dev_id}\n👤 **اسم العميل:**"
          f" {dev_info['name']}\n📱 **رقم الهاتف:** {phone_str}\n"
      )

  if results:
    response = (
        f"🔍 **نتائج البحث عن ({query}):**\n\n"
        + "\n-------------------\n".join(results[:10])
    )
    await update.message.reply_text(response, parse_mode="Markdown")
  else:
    await update.message.reply_text(
        "❌ لم يتم العثور على أي جهاز بهذا الرقم أو الاسم."
    )


if __name__ == "__main__":
  app = ApplicationBuilder().token(BOT_TOKEN).build()
  app.add_handler(CommandHandler("start", start))
  app.add_handler(
      MessageHandler(filters.TEXT & (~filters.COMMAND), handle_search)
  )
  app.run_polling()
